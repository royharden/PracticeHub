-- exception report (R6-REQ-032), one row per finding per report run. Append-only.
CREATE TABLE IF NOT EXISTS payments_ledger.oig_exception_report (
  tenant_id text NOT NULL,
  report_id text NOT NULL,
  finding_key text NOT NULL,
  kind text NOT NULL CHECK (kind IN ('double-bill-same-rail', 'double-bill-cross-rail')),
  patient_ref text NOT NULL,
  service_ref text NOT NULL,
  service_date date NOT NULL,
  charge_ids text[] NOT NULL CHECK (cardinality(charge_ids) >= 2),
  rails text[] NOT NULL CHECK (
    cardinality(rails) >= 1
    AND rails <@ ARRAY['insurance', 'membership', 'cash']::text[]
  ),
  generated_at timestamptz NOT NULL,
  synthetic boolean NOT NULL CHECK (synthetic),
  PRIMARY KEY (tenant_id, report_id, finding_key),
  CHECK ((kind = 'double-bill-cross-rail') = (cardinality(rails) > 1))
);


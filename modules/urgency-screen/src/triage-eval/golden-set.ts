export interface ConfirmedMissInput {
  readonly inboundId: string;
  readonly language: ScreenLanguage;
  readonly channel: InboundChannel;
  readonly afterHours: boolean;
  readonly text: string;
  readonly observedClass: UrgencyClass;
  readonly observedClassifierVersion: string;
  readonly correctedClass: UrgencyClass;
  readonly failureMode: FailureMode;
  readonly reviewerId: string;
  readonly reviewerKind: 'human' | 'ai';
  readonly synthetic: true;
}

/**
 * Feedback loop (REQ-AI-065 AC1, REQ-COMM-041 AC3/EX3): a human-confirmed miss becomes a golden
 * case in a new revision. No AI component may confirm its own correction.
 */
export function addConfirmedMiss(set: GoldenSet, miss: ConfirmedMissInput): GoldenSet {
  if (miss.synthetic !== true) throw new Error('confirmed miss must be synthetic');
  if (miss.reviewerKind !== 'human') {
    throw new Error('a confirmed miss needs a human reviewer; no silent self-correction');
  }
  if (miss.reviewerId.trim() === '') throw new Error('a confirmed miss names its reviewer');
  if (miss.observedClass === miss.correctedClass) {
    throw new Error('not a miss: the corrected class equals the observed class');
  }
  const caseId = `miss-${miss.inboundId}`;
  const record: ConfirmedMissRecord = Object.freeze({
    caseId,
    inboundId: miss.inboundId,
    observedClass: miss.observedClass,
    observedClassifierVersion: miss.observedClassifierVersion,
    correctedClass: miss.correctedClass,
    reviewerId: miss.reviewerId,
    reviewerKind: 'human',
  });
  return createGoldenSet({
    revision: set.revision + 1,
    parentRevision: set.revision,
    cases: [
      ...set.cases,
      goldenCase(
        caseId,
        miss.language,
        miss.channel,
        miss.text,
        miss.correctedClass,
        miss.failureMode,
        'confirmed-miss',
        miss.afterHours,
      ),
    ],
    misses: [...set.misses, record],
  });
}

import { createHash } from 'node:crypto';
import type { InboundChannel, ScreenLanguage, UrgencyClass } from '../types.js';
import {
  GOLDEN_SET_SERIES,
  type ConfirmedMissRecord,
  type FailureMode,
  type GoldenCase,
  type GoldenCaseSource,
  type GoldenSet,
} from './types.js';

export const MATRIX_LANGUAGES: readonly ScreenLanguage[] = Object.freeze(['en', 'es', 'unknown']);

/** U+2019, the apostrophe phone keyboards substitute for `'`. Spelled out so it is not misread. */
export const RIGHT_SINGLE_QUOTE = String.fromCodePoint(0x2019);

function goldenCase(
  caseId: string,
  language: ScreenLanguage,
  channel: InboundChannel,
  text: string,
  expected: UrgencyClass,
  failureMode: FailureMode,
  source: GoldenCaseSource,
  afterHours = true,
): GoldenCase {
  return Object.freeze({
    caseId,
    language,
    channel,
    afterHours,
    text,
    expected,
    failureMode,
    source,
    synthetic: true,
  });
}

/**
 * Validates and freezes a golden set. Every matrix language needs at least one urgent and one
 * routine case: an empty cell would let the language matrix pass without looking at anything.
 */
export function createGoldenSet(input: {
  readonly revision: number;
  readonly parentRevision: number | null;
  readonly cases: readonly GoldenCase[];
  readonly misses: readonly ConfirmedMissRecord[];
}): GoldenSet {
  if (!Number.isInteger(input.revision) || input.revision < 1) {
    throw new Error('golden set revision must be a positive integer');
  }
  const ids = new Set<string>();
  const texts = new Set<string>();
  for (const item of input.cases) {
    if (item.synthetic !== true) throw new Error(`golden case ${item.caseId} is not synthetic`);
    if (item.text.trim() === '') throw new Error(`golden case ${item.caseId} has no text`);
    if (ids.has(item.caseId)) throw new Error(`duplicate golden case id ${item.caseId}`);
    const textKey = `${item.language}\u0000${item.text}`;
    if (texts.has(textKey)) throw new Error(`duplicate golden case text in ${item.language}`);
    ids.add(item.caseId);
    texts.add(textKey);
  }
  for (const language of MATRIX_LANGUAGES) {
    for (const expected of ['urgent', 'routine'] as const) {
      const covered = input.cases.some(
        (item) => item.language === language && item.expected === expected,
      );
      if (!covered) throw new Error(`golden set has no ${expected} case for language ${language}`);
    }
  }
  return Object.freeze({
    series: GOLDEN_SET_SERIES,
    revision: input.revision,
    parentRevision: input.parentRevision,
    cases: Object.freeze([...input.cases]),
    misses: Object.freeze([...input.misses]),
    synthetic: true,
  });
}

export function goldenSetDigest(set: GoldenSet): string {
  return createHash('sha256')
    .update(
      JSON.stringify({
        series: set.series,
        revision: set.revision,
        parentRevision: set.parentRevision,
        cases: set.cases,
        misses: set.misses,
      }),
    )
    .digest('hex');
}


function relabelled(cases: readonly GoldenCase[]): GoldenCase[] {
  const byId = new Map(cases.map((item) => [item.caseId, item]));
  return CONCEPT_EXEMPLARS.flatMap((caseId) => {
    const exemplar = byId.get(caseId);
    if (exemplar === undefined) throw new Error(`concept exemplar ${caseId} is missing`);
    const other = exemplar.language === 'en' ? 'es' : 'en';
    return [
      goldenCase(
        `${caseId}~unknown`,
        'unknown',
        exemplar.channel,
        exemplar.text,
        'urgent',
        'language-unknown',
        'seed',
      ),
      goldenCase(
        `${caseId}~as-${other}`,
        other,
        exemplar.channel,
        exemplar.text,
        'urgent',
        'language-mislabel',
        'seed',
      ),
    ];
  });
}

/** Keeps the first case for each (language, text): later sources that repeat one add nothing. */
function firstOccurrences(cases: readonly GoldenCase[]): GoldenCase[] {
  const seen = new Set<string>();
  return cases.filter((item) => {
    const key = `${item.language}|${item.text}`;
    if (seen.has(key)) return false;
    seen.add(key);
    return true;
  });
}

